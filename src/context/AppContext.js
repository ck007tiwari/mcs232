import React, { createContext, useContext, useState } from 'react';
import { toast } from 'react-toastify';
import { 
  dummyUser, 
  dummyAdmin,
  validCredentials,
  dummySubjects, 
  dummyPdfs, 
  dummyProgress, 
  dummyQuestions,
  dummyChartData,
  dummyRecentActivity
} from '../data/dummyData';

const AppContext = createContext();

export const useApp = () => {
  const context = useContext(AppContext);
  if (!context) {
    throw new Error('useApp must be used within an AppProvider');
  }
  return context;
};

export const AppProvider = ({ children }) => {
  const [user, setUser] = useState(dummyUser);
  const [isAuthenticated, setIsAuthenticated] = useState(true);
  const [subjects, setSubjects] = useState(dummySubjects);
  const [pdfs, setPdfs] = useState(dummyPdfs);
  const [progress, setProgress] = useState(dummyProgress);
  const [questions, setQuestions] = useState(dummyQuestions);
  const [chartData] = useState(dummyChartData);
  const [recentActivity] = useState(dummyRecentActivity);
  const [currentPdf, setCurrentPdf] = useState(null);
  const [sidebarOpen, setSidebarOpen] = useState(false);

  // Authentication functions
  const login = (email, password) => {
    // Check against valid credentials
    const credential = validCredentials.find(
      cred => cred.email === email && cred.password === password
    );
    
    if (credential) {
      setUser(credential.user);
      setIsAuthenticated(true);
      return { success: true, user: credential.user };
    }
    return { success: false, message: "Invalid credentials" };
  };

  const logout = () => {
    toast.info('You have been logged out. See you soon!', {
      icon: '👋'
    });
    setIsAuthenticated(false);
    setUser(null);
  };

  const register = (userData) => {
    // Simulate registration
    setUser({ ...dummyUser, ...userData });
    setIsAuthenticated(true);
    return true;
  };

  // PDF functions
  const getPdfsBySubject = (subjectId) => {
    const accessiblePdfs = getAccessiblePdfs();
    return accessiblePdfs.filter(pdf => pdf.subjectId === subjectId);
  };

  const getProgressByPdf = (pdfId) => {
    return progress.find(p => p.pdfId === pdfId);
  };

  const getQuestionsByPdf = (pdfId) => {
    return questions.filter(q => q.pdfId === pdfId);
  };

  // Progress functions
  const updateProgress = (pdfId, newProgress) => {
    setProgress(prev => 
      prev.map(p => p.pdfId === pdfId ? { ...p, ...newProgress } : p)
    );
  };

  // Question functions
  const askQuestion = (pdfId, questionText, pageContext) => {
    const newQuestion = {
      questionId: `q_${Date.now()}`,
      userId: user.userId,
      pdfId,
      questionText,
      answerText: "This is a simulated AI response. In the real application, this would be generated by the AI service based on the PDF content and context.",
      pageContext,
      confidenceScore: 0.85 + Math.random() * 0.15,
      timestamp: new Date().toISOString()
    };
    setQuestions(prev => [newQuestion, ...prev]);
    return newQuestion;
  };

  // Admin functions
  const deletePdf = (pdfId) => {
    if (user?.role !== 'admin') {
      return { success: false, message: "Unauthorized: Admin access required" };
    }
    
    // Remove PDF from pdfs array
    setPdfs(prev => prev.filter(pdf => pdf.pdfId !== pdfId));
    
    // Remove associated progress records
    setProgress(prev => prev.filter(p => p.pdfId !== pdfId));
    
    // Remove associated questions
    setQuestions(prev => prev.filter(q => q.pdfId !== pdfId));
    
    return { success: true, message: "PDF deleted successfully" };
  };

  // Helper function to check admin permissions
  const isAdmin = () => user?.role === 'admin';

  // PDF upload function
  const uploadPdf = (pdfData) => {
    setPdfs(prev => [...prev, pdfData]);
    
    // Update subject PDF count
    setSubjects(prev => 
      prev.map(subject => 
        subject.subjectId === pdfData.subjectId 
          ? { ...subject, totalPdfs: subject.totalPdfs + 1, totalPages: subject.totalPages + pdfData.totalPages }
          : subject
      )
    );
    
    return { success: true, message: "PDF uploaded successfully" };
  };

  // Get PDFs with access control
  const getAccessiblePdfs = () => {
    if (user?.role === 'admin') {
      return pdfs; // Admin can see all PDFs
    } else {
      return pdfs.filter(pdf => 
        pdf.isPublic || pdf.uploadedBy === user?.userId
      );
    }
  };

  // Get all PDFs for admin (used in admin dashboard)
  const getAllPdfs = () => {
    return pdfs;
  };

  const value = {
    // State
    user,
    isAuthenticated,
    subjects,
    pdfs,
    progress,
    questions,
    chartData,
    recentActivity,
    currentPdf,
    sidebarOpen,
    
    // Setters
    setCurrentPdf,
    setSidebarOpen,
    
    // Functions
    login,
    logout,
    register,
    getPdfsBySubject,
    getProgressByPdf,
    getQuestionsByPdf,
    updateProgress,
    askQuestion,
    deletePdf,
    isAdmin,
    uploadPdf,
    getAccessiblePdfs,
    getAllPdfs
  };

  return (
    <AppContext.Provider value={value}>
      {children}
    </AppContext.Provider>
  );
};